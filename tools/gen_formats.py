#!/usr/bin/env python3
"""Convert KeyCopier's key_formats.c (MIT, zinongli/KeyCopier) into a C++ table for the Mayhem app.
tan((180-drill_angle)/2 deg) is precomputed so the device needs no libm. Lengths are written in 1/10000 inch and the
tangent in 1/1000, so the app uses integer math only (the M0 core has no FPU)."""
import re, math, sys
src = open(sys.argv[1]).read()
blocks = re.findall(r"\{\s*\.manufacturer.*?\}\s*[,;]?", src, re.S)
rows = []
for b in blocks:
    b = re.sub(r"//[^\n]*", "", b)
    f = dict(re.findall(r"\.(\w+)\s*=\s*(\"[^\"]*\"|[-\d.]+)", b))
    g = lambda k, d="0": f.get(k, d)
    ang = float(g("drill_angle", "90"))
    tan = math.tan(math.radians((180 - ang) / 2))
    u = lambda k: round(float(g(k)) * 10000)  # inches -> 1/10000 inch
    rows.append(f'    {{{g("manufacturer")}, {g("format_name")}, {g("sides")}, {g("stop")}, '
                f'{u("first_pin_inch")}, {u("pin_increment_inch")}, {g("pin_num")}, {u("pin_width_inch")}, '
                f'{round(tan * 1000)}, {u("elbow_inch")}, {u("uncut_depth_inch")}, {u("depth_step_inch")}, '
                f'{g("min_depth_ind")}, {g("max_depth_ind")}, {g("macs")}, {g("clearance")}, {u("last_pin_inch")}}},')
print(f"// GENERATED by tools/gen_formats.py from zinongli/KeyCopier key_formats.c (MIT). {len(rows)} formats.")
print("// Lengths are in 1/10000 inch, the tangent in 1/1000 (integer math, no FPU on the M0).")
print('#include "key_formats.hpp"\nnamespace ui::external_app::key_copier {')
print("const KeyFormat all_formats[FORMAT_NUM] = {")
print("\n".join(rows))
print("};\n}")
print(f"// count={len(rows)}", file=sys.stderr)
